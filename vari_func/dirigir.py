
# Verificar idade para dirigir

idade = int(input("👤 Digite sua idade: "))

if idade > 18:
    print("🚗 Indivíduo possui idade mínima para dirigir")

elif idade == 18:
    print("⚠️ Você tem 18 anos! Verifique os requisitos legais para dirigir.")

else:
    print("😂 Nem pense em dirigir ainda! Você é de menor de idade, mocinho! Vai brincar!")
